import AppKit
import EventKit
import ConfigKit

// Clipboard history, quick notes, next calendar event, and sound feedback.
extension DockWidgets {

    // MARK: Clipboard history (memory only; never written to disk)

    private static var clipboardTimer: Timer?
    private static var lastChangeCount = NSPasteboard.general.changeCount
    /// Most recent first, up to 20 texts.
    public private(set) static var clipboardHistory: [String] = []

    /// macOS posts no clipboard notification, so check the change counter once a second
    /// (one integer read) — only while a Clipboard widget is on a Dock.
    static func startClipboardWatch() {
        guard clipboardTimer == nil else { return }
        let timer = Timer(timeInterval: 1, repeats: true) { _ in captureClipboard() }
        timer.tolerance = 0.5
        RunLoop.main.add(timer, forMode: .common)
        clipboardTimer = timer
    }

    private static func captureClipboard() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        // Skip what password managers mark as secret or temporary (nspasteboard.org convention).
        let skip: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                 "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        if let types = pb.types, types.contains(where: { skip.contains($0.rawValue) }) { return }
        guard let text = pb.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines),
              !text.isEmpty, text.count < 10_000 else { return }
        clipboardHistory.removeAll { $0 == text }
        clipboardHistory.insert(text, at: 0)
        if clipboardHistory.count > 20 { clipboardHistory.removeLast() }
    }

    /// Put an old entry back on the clipboard (ready to paste).
    static func restoreClipboard(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        lastChangeCount = pb.changeCount
        clipboardHistory.removeAll { $0 == text }
        clipboardHistory.insert(text, at: 0)
    }

    static func clearClipboardHistory() { clipboardHistory.removeAll() }

    // MARK: Quick notes

    static var notesURL: URL { shelfDirectory.deletingLastPathComponent().appendingPathComponent("Notes.txt") }

    // MARK: Next calendar event

    static let eventStore = EKEventStore()
    private static var calendarObserver: NSObjectProtocol?
    private static var calendarAccess: Bool?

    /// Ask once for Calendar access (macOS shows its own prompt), then redraw on changes.
    static func startCalendar() {
        guard calendarAccess == nil else { return }
        calendarAccess = false
        eventStore.requestFullAccessToEvents { granted, _ in
            DispatchQueue.main.async {
                calendarAccess = granted
                NotificationCenter.default.post(name: changed, object: WidgetKind.calendar)
            }
        }
        calendarObserver = NotificationCenter.default.addObserver(forName: .EKEventStoreChanged, object: eventStore, queue: .main) { _ in
            NotificationCenter.default.post(name: changed, object: WidgetKind.calendar)
        }
        startUpdates(for: .clock)        // minute tick keeps "in 25m" current
    }

    /// Timed events from now until the end of tomorrow, soonest first.
    static func upcomingEvents(limit: Int = 8) -> [EKEvent] {
        guard calendarAccess == true else { return [] }
        let now = Date()
        let end = Calendar.current.date(byAdding: .day, value: 2, to: Calendar.current.startOfDay(for: now)) ?? now
        let predicate = eventStore.predicateForEvents(withStart: now.addingTimeInterval(-60 * 60), end: end, calendars: nil)
        return eventStore.events(matching: predicate)
            .filter { !$0.isAllDay && $0.endDate > now }
            .sorted { $0.startDate < $1.startDate }
            .prefix(limit).map { $0 }
    }

    static func eventLine(_ e: EKEvent) -> String {
        let f = DateFormatter()
        f.setLocalizedDateFormatFromTemplate(Calendar.current.isDateInToday(e.startDate) ? "jmm" : "EEE jmm")
        return "\(f.string(from: e.startDate))  \(e.title ?? "Event")"
    }

    static func calendarTile(size: CGFloat) -> NSImage {
        guard calendarAccess == true else { return tileImage(size: size, top: "CALENDAR", main: "—") }
        guard let next = upcomingEvents(limit: 1).first else { return tileImage(size: size, top: "NEXT", main: "Free") }
        let minutes = Int(next.startDate.timeIntervalSinceNow / 60)
        let main: String
        if minutes <= 0 { main = "Now" }
        else if minutes < 60 { main = "\(minutes)m" }
        else if minutes < 24 * 60 { main = "\(minutes / 60)h" }
        else { main = "1d+" }
        return tileImage(size: size, top: "NEXT", main: main)
    }

    static func calendarAccessibilityText() -> String {
        guard calendarAccess == true else { return "Next event. Calendar access not granted." }
        guard let next = upcomingEvents(limit: 1).first else { return "Next event: nothing scheduled" }
        return "Next event: " + eventLine(next)
    }
}

/// Optional subtle sounds (Settings ▸ General ▸ Accessibility ▸ Sounds).
public enum DockSound {
    public enum Kind { case launch, drop, remove }
    public static func play(_ kind: Kind) {
        guard DockAccess.prefs.sounds else { return }
        let name: String
        switch kind {
        case .launch: name = "Pop"
        case .drop:   name = "Tink"
        case .remove: name = "Bottle"
        }
        let sound = NSSound(named: name)
        sound?.volume = 0.35
        sound?.play()
    }
}
